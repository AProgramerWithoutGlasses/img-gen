import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { prepareEvidenceOutput } from './evidence-output.mjs';
import { chooseDialogOption } from './dialog-check.mjs';
import { unzipSync } from 'fflate';
import { chromium, expect } from '@playwright/test';
import { createServer } from 'vite';

const root=fileURLToPath(new URL('../../',import.meta.url));
const {url:output}=await prepareEvidenceOutput(process.argv.slice(2),{defaultDirectory:'frontend/outputs/auth-gallery'});
const server=await createServer({root,mode:'preview',server:{host:'127.0.0.1',port:5186,strictPort:true}});
const origin='http://127.0.0.1:5186';
const errors=[],results=[];
let browser;
try {
  await server.listen();
  browser=await chromium.launch({channel:process.platform==='win32'?'msedge':undefined});
  const page=await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error'&&!/Failed to load resource.*404/.test(message.text()))errors.push(message.text());});
  const shot=async name=>{
    await page.evaluate(()=>document.fonts.ready);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
    await page.screenshot({path:fileURLToPath(new URL(name+'.png',output))});
    results.push(name);
  };
  const login=async(username='admin',password='preview1234')=>{
    await page.getByLabel('用户名',{exact:true}).fill(username);
    await page.getByLabel('密码',{exact:true}).fill(password);
    await page.getByRole('button',{name:'登录',exact:true}).click();
    await expect(page.getByRole('button',{name:'我的账户',exact:true})).toBeVisible();
  };
  const logout=async()=>{
    await page.getByRole('button',{name:'我的账户',exact:true}).click();
    await page.locator('.account-menu').getByRole('button',{name:'退出登录',exact:true}).click();
    await expect(page.getByRole('button',{name:'登录',exact:true})).toBeVisible();
  };
  const archive=async(action,name,want)=>{
    const pending=page.waitForEvent('download');
    await action();
    const download=await pending;
    expect(download.suggestedFilename()).toMatch(/\.zip$/);
    const path=fileURLToPath(new URL(name+'.zip',output));
    await download.saveAs(path);
    expect(await download.failure()).toBeNull();
    const files=unzipSync(new Uint8Array(await readFile(path)));
    expect(Object.keys(files)).toHaveLength(want);
    for(const [filename,bytes] of Object.entries(files)){
      expect(filename).not.toMatch(/[\\/]/);
      expect(filename.startsWith('.')).toBe(false);
      expect(bytes.byteLength).toBeGreaterThan(0);
    }
    return files;
  };
  await page.goto(origin);
  await expect(page.locator('.login-brand')).toContainText('AiCraft');
  await shot('login-light');
  await page.getByRole('button',{name:'注册账号',exact:true}).click();
  await shot('register-light');
  await page.getByRole('button',{name:'返回登录',exact:true}).click();
  await login();
  await page.goto(origin+'/#/settings/appearance');
  await page.getByRole('button',{name:'深色',exact:true}).click();
  await logout();
  await shot('login-dark');
  await page.getByRole('button',{name:'注册账号',exact:true}).click();
  await shot('register-dark');
  await page.getByLabel('用户名',{exact:true}).fill('registered_user');
  await page.getByLabel('密码',{exact:true}).fill('1234567');
  await page.getByLabel('确认密码',{exact:true}).fill('1234567');
  await page.getByRole('button',{name:'注册并登录',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('8');
  await page.getByLabel('密码',{exact:true}).fill('密'.repeat(43));
  await page.getByLabel('确认密码',{exact:true}).fill('密'.repeat(43));
  await page.getByRole('button',{name:'注册并登录',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('128');
  await page.getByLabel('密码',{exact:true}).fill('register1234');
  await page.getByRole('button',{name:'显示密码',exact:true}).click();
  await expect(page.getByLabel('密码',{exact:true})).toHaveAttribute('type','text');
  await page.getByRole('button',{name:'隐藏密码',exact:true}).click();
  await expect(page.getByLabel('密码',{exact:true})).toHaveAttribute('type','password');
  await page.getByLabel('确认密码',{exact:true}).fill('different123');
  await page.getByRole('button',{name:'注册并登录',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('不一致');
  await page.getByLabel('确认密码',{exact:true}).fill('register1234');
  await page.getByRole('button',{name:'注册并登录',exact:true}).click();
  await expect(page.getByRole('button',{name:'我的账户',exact:true})).toBeVisible();
  await page.goto(origin+'/#/settings/account');
  await expect(page.locator('.account-details')).toContainText('普通用户');
  await expect(page.locator('.account-trigger-balance')).toContainText('0');
  await expect(page.getByRole('button',{name:'用户管理',exact:true})).toHaveCount(0);
  await page.reload();
  await expect(page.locator('.account-details')).toContainText('registered_user');
  await shot('registered-zero-credit-account');
  await logout();
  await login();
  await page.goto(origin+'/#/gallery');
  const tiles=page.locator('.gallery-tile');
  await expect.poll(()=>tiles.count()).toBeGreaterThanOrEqual(2);
  await tiles.first().hover();
  const compact=await tiles.first().locator('.image-card-actions').evaluate(element=>element.classList.contains('is-compact'));
  if(!compact)await expect(tiles.first().getByRole('button',{name:'继续修图',exact:true})).toBeVisible();
  await shot('gallery-hover');
  await tiles.first().getByRole('button',{name:'更多图片操作',exact:true}).click();
  await expect(page.getByRole('menu',{name:'图片操作',exact:true})).toBeVisible();
  await expect(page.getByRole('menuitem',{name:'查看大图',exact:true})).toHaveCount(0);
  await expect(page.getByRole('menuitem',{name:'复制提示词',exact:true})).toBeVisible();
  if(compact)await expect(page.getByRole('menuitem',{name:'继续修图',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await tiles.first().hover();
  await tiles.first().getByRole('checkbox').check();
  await tiles.nth(1).getByRole('checkbox').check();
  const galleryBar=page.getByRole('toolbar',{name:'图片整理',exact:true});
  await expect(galleryBar).toContainText('已选 2 张');
  await expect(galleryBar.getByRole('button',{name:'继续修图',exact:true})).toBeEnabled();
  await shot('gallery-selection');
  await archive(()=>galleryBar.getByRole('button',{name:'下载',exact:true}).click(),'gallery-originals',2);
  await galleryBar.getByRole('button',{name:'退出多选',exact:true}).click();
  await expect(galleryBar).toHaveCount(0);
  await page.getByRole('button',{name:'选择图片',exact:true}).click();
  await expect(galleryBar).toContainText('已选 0 张');
  await galleryBar.getByRole('button',{name:'全选',exact:true}).click();
  await expect(galleryBar).toContainText(`已选 ${await tiles.count()} 张`);
  await galleryBar.getByRole('button',{name:'取消全选',exact:true}).click();
  await expect(galleryBar).toContainText('已选 0 张');
  await page.keyboard.press('Escape');
  await expect(galleryBar).toHaveCount(0);
  await tiles.first().hover();
  if(compact){
    await tiles.first().getByRole('button',{name:'更多图片操作',exact:true}).click();
    await page.getByRole('menuitem',{name:'继续修图',exact:true}).click();
  } else await tiles.first().getByRole('button',{name:'继续修图',exact:true}).click();
  await expect(page).toHaveURL(/#\/create$/);
  await expect(page.locator('.attachment-item')).toHaveCount(1);
  await page.locator('.attachment-item').hover();
  await page.locator('.attachment-remove').click();
  const creation=page.getByRole('region',{name:'图像创作',exact:true});
  await chooseDialogOption(page,creation.getByRole('combobox',{name:'生成数量',exact:true}),'2张');
  await creation.getByRole('textbox',{name:'提示词',exact:true}).fill('工作台批量下载验证');
  await creation.getByRole('button',{name:'生成',exact:true}).click();
  await expect(creation.locator('.result-card.is-ready')).toHaveCount(2,{timeout:15000});
  await creation.locator('.result-card').first().hover();
  await creation.getByRole('checkbox',{name:'选择第 1 张图片',exact:true}).check();
  await creation.getByRole('checkbox',{name:'选择第 2 张图片',exact:true}).check();
  const workbenchBar=page.getByRole('toolbar',{name:'已选图片操作',exact:true});
  await expect(workbenchBar.getByRole('button',{name:'继续修图',exact:true})).toBeEnabled();
  await expect(creation.locator('.workbench-prompt')).toHaveCSS('font-size','18px');
  await shot('workbench-selection');
  await archive(()=>workbenchBar.getByRole('button',{name:'下载',exact:true}).click(),'workbench-originals',2);
  await workbenchBar.getByRole('button',{name:'退出多选',exact:true}).click();
  const filenameFiles=await archive(()=>page.evaluate(async()=>{
    const {downloadImages}=await import('/src/lib/images.ts');
    await downloadImages(['../same.png','..\\same.png','SAME.PNG'].map((name,i)=>({id:'name-'+i,name,url:'data:image/png;base64,AQID',createdAt:new Date().toISOString()})));
  }),'safe-duplicate-names',3);
  expect(Object.keys(filenameFiles).map(name=>name.toLowerCase()).length).toBe(new Set(Object.keys(filenameFiles).map(name=>name.toLowerCase())).size);
  for(const value of Object.values(filenameFiles))expect([...value]).toEqual([1,2,3]);
  await page.route('**/missing-download-original',route=>route.fulfill({status:404,body:'missing'}));
  let unexpectedDownload=false;
  page.on('download',()=>{unexpectedDownload=true;});
  const failure=await page.evaluate(async()=>{
    const {downloadImages}=await import('/src/lib/images.ts');
    try {await downloadImages([{id:'missing',name:'missing.png',url:'/missing-download-original'}]);return '';}
    catch(error){return error.message;}
  });
  expect(failure).toContain('未生成下载包');
  expect(unexpectedDownload).toBe(false);
  expect(errors).toEqual([]);
  await writeFile(new URL('verification.json',output),JSON.stringify({passed:results,errors,registrationAndReload:true,passwordLimits:true,galleryAndWorkbenchZip:true,originalBytesPreserved:true,safeDuplicateNames:true,noPartialArchiveOnFailure:true},null,2));
  console.log(JSON.stringify({passed:results.length,errors:errors.length,registrationAndReload:true,galleryAndWorkbenchZip:true,safeDuplicateNames:true,noPartialArchiveOnFailure:true}));
} finally {
  await browser?.close();
  await server.close();
}
